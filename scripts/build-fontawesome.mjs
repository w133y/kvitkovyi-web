// Builds the site's own Font Awesome subset: only the icons the code uses.
//   npm pack @fortawesome/fontawesome-free@6.5.1 && tar -xzf <tgz>
//   node scripts/build-fontawesome.mjs <path-to-extracted>/package
// Writes app/fontawesome.css and public/fonts/fa/*.woff2 (needs Python with
// fonttools + brotli for the font subsetting). Re-run after adding an icon —
// an icon missing from the subset just renders as nothing.

import fs from "fs";
import path from "path";
import { execFileSync } from "child_process";

const pkg = process.argv[2];
if (!pkg) throw new Error("usage: node scripts/build-fontawesome.mjs <fontawesome-free package dir>");
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Z]:)/, "$1")), "..");

// Every fa-* token in the source — icon names and modifiers alike; tokens
// that aren't icons simply never match an icon rule below.
const used = new Set(
  execFileSync(
    "git",
    // Not the generated file itself, or every icon would count as used on a re-run.
    ["grep", "-ohE", "\\bfa-[a-z0-9-]+", "--", "app", "components", "lib", "public/*.css", ":!app/fontawesome.css"],
    { cwd: root }
  )
    .toString()
    .split(/\s+/)
    .filter(Boolean)
);

const css = fs.readFileSync(path.join(pkg, "css/all.css"), "utf8").replace(/\/\*[\s\S]*?\*\//g, "");

// Top-level blocks: "prelude { body }" with nested braces for @media/@keyframes.
const blocks = [];
for (let i = 0; i < css.length; ) {
  const open = css.indexOf("{", i);
  if (open === -1) break;
  let depth = 0, j = open;
  for (; j < css.length; j++) {
    if (css[j] === "{") depth++;
    else if (css[j] === "}" && --depth === 0) break;
  }
  blocks.push({ prelude: css.slice(i, open).trim(), body: css.slice(open + 1, j).trim() });
  i = j + 1;
}

const ICON_SELECTOR = /^\.fa-([a-z0-9-]+)::?before$/;
const FONT_FILE = { "fa-solid-900": "solid", "fa-regular-400": "regular", "fa-brands-400": "brands" };
const codepoints = new Set();
const out = [];
for (const { prelude, body } of blocks) {
  if (prelude.startsWith("@font-face")) {
    const file = Object.keys(FONT_FILE).find((f) => body.includes(`${f}.`));
    const family = body.match(/font-family:\s*([^;]+);/)[1];
    // The v4/v5-compatibility families: the site only uses v6 class names.
    if (!file || !family.includes("Font Awesome 6")) continue;
    const weight = body.match(/font-weight:\s*([^;]+);/)[1];
    out.push(
      `@font-face{font-family:${family};font-style:normal;font-weight:${weight};font-display:swap;` +
        `src:url(/fonts/fa/${FONT_FILE[file]}.woff2) format("woff2")}`
    );
    continue;
  }
  const selectors = prelude.split(",").map((s) => s.trim());
  if (selectors.every((s) => ICON_SELECTOR.test(s))) {
    const keep = selectors.filter((s) => used.has(`fa-${s.match(ICON_SELECTOR)[1]}`));
    if (keep.length === 0) continue;
    const cp = body.match(/content:\s*"\\([0-9a-f]+)"/i);
    if (cp) codepoints.add(parseInt(cp[1], 16));
    out.push(`${keep.join(",")}{${body}}`);
    continue;
  }
  out.push(`${prelude}{${body}}`);
}

const minified = out
  .join("\n")
  .replace(/\s+/g, " ")
  .replace(/\s*([{}:;,>])\s*/g, "$1")
  .replace(/;}/g, "}");
fs.writeFileSync(
  path.join(root, "app/fontawesome.css"),
  `/* Generated by scripts/build-fontawesome.mjs — Font Awesome Free 6.5.1 (CC BY 4.0 icons,\n   SIL OFL fonts, MIT code), subset to the icons this site uses. Do not edit by hand. */\n${minified}\n`
);

fs.mkdirSync(path.join(root, "public/fonts/fa"), { recursive: true });
const unicodes = [...codepoints].map((c) => "U+" + c.toString(16)).join(",");
for (const [file, name] of Object.entries(FONT_FILE)) {
  execFileSync("python", [
    "-m", "fontTools.subset", path.join(pkg, "webfonts", `${file}.ttf`),
    `--unicodes=${unicodes}`, "--flavor=woff2", "--no-hinting", "--desubroutinize",
    `--output-file=${path.join(root, "public/fonts/fa", `${name}.woff2`)}`,
  ]);
}
console.log(`icons kept: ${codepoints.size}, css: ${minified.length} bytes`);
for (const name of Object.values(FONT_FILE)) {
  console.log(`${name}.woff2: ${fs.statSync(path.join(root, "public/fonts/fa", `${name}.woff2`)).size} bytes`);
}
